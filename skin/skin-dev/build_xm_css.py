# -*- coding: utf-8 -*-
"""Build the Christmas skin stylesheet.

    python build_xm_css.py            -> <pkg>/skin/christmas.css

css-xm/10-tokens.gen.css  is regenerated from the app's resolved dark palette (inline_dark_3114.json: the
                          client writes it as inline custom properties on <html>, so every token needs
                          !important). Greys become a winter-night navy, the blue accent becomes candle gold.
css-xm/20-decor.css       hand-written decoration layer; `asset(name.ext)` is replaced by a data: URI of
                          assets/<name.ext>
"""
import base64, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "launcher", "build", "MiniMaxCodeBoot", "skin", "christmas.css")
CSS = os.path.join(HERE, "css-xm")
sys.stdout.reconfigure(encoding="utf-8")

# dark-mode value -> Christmas value
RAMP = {
    # neutral greys -> winter night (the navy of the forest sky), text -> warm snow
    "#171717": "#07131f", "#1c1c1c": "#0c1b2a", "#262626": "#132638", "#303030": "#1b3147",
    "#4a4a4a": "#34506a", "#666666": "#5a7790", "#949494": "#8ba2b6", "#adadad": "#aabdcd",
    "#cccccc": "#c9d6e0", "#ededed": "#f0efe9", "#f5f5f5": "#f6f5f0", "#fafafa": "#fbfaf7",
    # blue accent -> candle gold
    "#0077d9": "#e3a22c", "#0094fc": "#f2b84b", "#68c0ff": "#ffd98a", "#004b96": "#8f5f12",
    "#00244d": "#4a3008", "#0075d4": "#dc9a26", "#0077d966": "#e3a22c66",
    "#0064ab1a": "#f2b84b1a", "#0064ab26": "#f2b84b26", "#0078ff1a": "#f2b84b1a",
    "#0000003d": "#01060c3d", "#00000080": "#01060c99",
}

INK_ON_GOLD = "#241803"
MANUAL = {
    "bg_interaction_primary_default": "#f2b84b",
    "bg_interaction_primary_selected": "#f2b84b",
    "bg_interaction_primary_hover": "#f7c766",
    "bg_interaction_primary_press": "#dc9a26",
    # a disabled primary button stays a mid-tone with dark ink, as in the stock theme: the send arrow
    # is drawn in the *default* ink even while disabled, so a dark disabled button would hide it
    "bg_interaction_primary_inactive": "#52708d",
    "bg_interaction_secondary_selected": "#17324c",
    "bg_status_tag": "#f2b84b",
    "shadow_default": "#01060c99",
    "utility_scrollbar": "#8ba2b640",
    "mavis-composer-placeholder-color": "#5f7c95",
    **{f"text_on_accent_{s}": INK_ON_GOLD for s in ("default", "hover", "press", "inactive")},
    **{f"icon_on_accent_{s}": INK_ON_GOLD for s in ("default", "hover", "press", "inactive")},
}

# ramps referenced through var() (not inlined by the app)
PRIMITIVES = """
  --gray_50: #fbfaf7; --gray_75: #f6f5f0; --gray_100: #f0efe9; --gray_200: #c9d6e0;
  --gray_300: #aabdcd; --gray_400: #8ba2b6; --gray_500: #5a7790; --gray_600: #34506a;
  --gray_700: #1b3147; --gray_800: #132638; --gray_900: #0c1b2a; --gray_1000: #07131f;
  --blue_25: #fffaee; --blue_50: #fff1d2; --blue_75: #ffe6b0; --blue_100: #ffd98a;
  --blue_200: #fbcb6b; --blue_300: #f7c259; --blue_400: #f2b84b; --blue_500: #e3a22c;
  --blue_600: #bf8420; --blue_700: #8f5f12; --blue_800: #4a3008; --blue_900: #2a1b04; --blue_1000: #160e02;
  --terminal_selection: #34506a; --terminal_cursor: #f7c259;
"""


def remap(v):
    v = v.lower()
    if v in RAMP:
        return RAMP[v]
    m = re.fullmatch(r"#ffffff([0-9a-f]{2})", v)
    if m:
        return "#e3eeff" + m.group(1)      # white veils pick up a little moonlight
    m = re.fullmatch(r"#0a0a0a([0-9a-f]{2})", v)
    if m:
        return "#02080f" + m.group(1)
    return v


def tokens():
    inline = json.load(open(os.path.join(HERE, "inline_dark_3114.json"), encoding="utf-8"))["value"]
    lines = []
    for k, v in inline.items():
        name = k[2:]
        if not re.fullmatch(r"#[0-9a-fA-F]{3,8}", v.strip()):
            continue
        new = MANUAL.get(name, remap(v.strip()))
        lines.append(f"  {k}: {new} !important;")
    for name, val in MANUAL.items():
        if f"--{name}" not in inline:
            lines.append(f"  --{name}: {val} !important;")
    head = ("/* generated by build_xm_css.py from the app's resolved dark palette — do not edit */\n"
            ":root {\n  color-scheme: dark !important;\n}\n\n")
    return head + "html[data-hwskin] {" + PRIMITIVES + "\n".join(lines) + "\n}\n"


def inline_assets(css):
    missing = []

    def sub(m):
        name = m.group(1)
        path = os.path.join(HERE, "assets", name)
        mime = {"png": "image/png", "webp": "image/webp", "svg": "image/svg+xml", "jpg": "image/jpeg"}[name.rsplit(".", 1)[1]]
        if not os.path.exists(path):
            missing.append(name)
            return f'url("assets/{name}")'
        data = base64.b64encode(open(path, "rb").read()).decode()
        return f'url("data:{mime};base64,{data}")'

    out = re.sub(r"asset\(([\w.\-]+)\)", sub, css)
    if missing:
        print("WARNING: missing art files, their URLs were left relative instead of inlined:",
              ", ".join(sorted(set(missing))))
        print("         Put the files in skin/skin-dev/assets/ and run this again.")
    return out


if __name__ == "__main__":
    os.makedirs(CSS, exist_ok=True)
    gen = tokens()
    open(os.path.join(CSS, "10-tokens.gen.css"), "w", encoding="utf-8", newline="\n").write(gen)
    parts = [gen]
    decor = os.path.join(CSS, "20-decor.css")
    if os.path.exists(decor):
        parts.append(open(decor, encoding="utf-8").read())
    css = inline_assets("\n".join(parts))
    tmp = OUT + ".tmp"
    open(tmp, "w", encoding="utf-8", newline="\n").write(css)
    os.replace(tmp, OUT)
    print(f"wrote {OUT} ({len(css) / 1024:.0f} KB, {gen.count('!important')} token overrides)")

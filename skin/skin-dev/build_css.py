# -*- coding: utf-8 -*-
"""Build the Halloween skin stylesheet.

    python build_css.py            -> <pkg>/skin/halloween.css

css/10-tokens.gen.css  is regenerated from inline_dark.json (the app's resolved dark palette, which it
                       writes as inline custom properties on <html>, so every token needs !important)
css/20-decor.css       hand-written decoration layer; `asset(name.ext)` is replaced by a data: URI of
                       assets/<name.ext>
"""
import base64, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
# The launcher package sits next to this source tree: <root>/skin/skin-dev -> <root>/launcher/build/...
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.environ.get("MC_HALLOWEEN_CSS") or os.path.join(
    ROOT, "launcher", "build", "MiniMaxCodeBoot", "skin", "halloween.css")
sys.stdout.reconfigure(encoding="utf-8")

# dark-mode value -> Halloween value
RAMP = {
    # neutral greys -> plum night
    "#171717": "#130e19", "#1c1c1c": "#1b1423", "#262626": "#261c31", "#303030": "#32263f",
    "#4a4a4a": "#4b3d5c", "#666666": "#6f5f84", "#949494": "#9d8db2", "#adadad": "#b8a9cc",
    "#cccccc": "#d3c7e1", "#ededed": "#eee5f5", "#f5f5f5": "#f4eef9", "#fafafa": "#faf6fc",
    # blue accent -> pumpkin
    "#0077d9": "#f07514", "#0094fc": "#ff8a1f", "#68c0ff": "#ffb066", "#004b96": "#9e4708",
    "#00244d": "#4d2306", "#0075d4": "#e8740f", "#0077d966": "#f0751466",
    "#0064ab1a": "#ff8a1f1a", "#0064ab26": "#ff8a1f26", "#0078ff1a": "#ff8a1f1a",
    "#0000003d": "#0a06123d", "#00000080": "#0a061299",
}

INK_ON_PUMPKIN = "#1e1007"
MANUAL = {
    "bg_interaction_primary_default": "#ff8a1f",
    "bg_interaction_primary_selected": "#ff8a1f",
    "bg_interaction_primary_hover": "#ff9e45",
    "bg_interaction_primary_press": "#e8740f",
    "bg_interaction_primary_inactive": "#3a2d4a",
    "text_label_primary_inactive": "#a493b8",
    "icon_interaction_primary_inactive": "#a493b8",
    "bg_interaction_secondary_selected": "#2e2140",
    "bg_status_tag": "#ff8a1f",
    "shadow_default": "#05020a99",
    "utility_scrollbar": "#9d8db240",
    "mavis-composer-placeholder-color": "#7d6d92",
    **{f"text_on_accent_{s}": INK_ON_PUMPKIN for s in ("default", "hover", "press", "inactive")},
    **{f"icon_on_accent_{s}": INK_ON_PUMPKIN for s in ("default", "hover", "press", "inactive")},
}

# ramps referenced through var() (not inlined by the app)
PRIMITIVES = """
  --gray_50: #faf6fc; --gray_75: #f4eef9; --gray_100: #eee5f5; --gray_200: #d3c7e1;
  --gray_300: #b8a9cc; --gray_400: #9d8db2; --gray_500: #6f5f84; --gray_600: #4b3d5c;
  --gray_700: #32263f; --gray_800: #261c31; --gray_900: #1b1423; --gray_1000: #130e19;
  --blue_25: #fff7ef; --blue_50: #ffebd6; --blue_75: #ffd7ad; --blue_100: #ffc285;
  --blue_200: #ffb066; --blue_300: #ff9e45; --blue_400: #ff8a1f; --blue_500: #f07514;
  --blue_600: #cc5e0b; --blue_700: #9e4708; --blue_800: #4d2306; --blue_900: #2b1404; --blue_1000: #170a02;
  --terminal_selection: #4b3d5c; --terminal_cursor: #ff9e45;
"""


def remap(v):
    v = v.lower()
    if v in RAMP:
        return RAMP[v]
    m = re.fullmatch(r"#ffffff([0-9a-f]{2})", v)
    if m:
        return "#ece0ff" + m.group(1)
    m = re.fullmatch(r"#0a0a0a([0-9a-f]{2})", v)
    if m:
        return "#0a0612" + m.group(1)
    return v


def tokens():
    inline = json.load(open(os.path.join(HERE, "inline_dark.json"), encoding="utf-8"))["value"]
    lines = []
    for k, v in inline.items():
        name = k[2:]
        if not re.fullmatch(r"#[0-9a-fA-F]{3,8}", v.strip()):
            continue
        new = MANUAL.get(name, remap(v.strip()))
        lines.append(f"  {k}: {new} !important;")
    for name, val in MANUAL.items():
        if f"--{name}" not in inline:
            lines.append(f"  --{name}: {val} !important;")
    head = ("/* generated by build_css.py from the app's resolved dark palette — do not edit */\n"
            ":root {\n  color-scheme: dark !important;\n}\n\n")
    return head + "html[data-hwskin] {" + PRIMITIVES + "\n".join(lines) + "\n}\n"


def inline_assets(css):
    missing = []

    def sub(m):
        name = m.group(1)
        path = os.path.join(HERE, "assets", name)
        mime = {"png": "image/png", "webp": "image/webp", "svg": "image/svg+xml", "jpg": "image/jpeg"}[name.rsplit(".", 1)[1]]
        if not os.path.exists(path):
            missing.append(name)
            return f'url("assets/{name}")'
        data = base64.b64encode(open(path, "rb").read()).decode()
        return f'url("data:{mime};base64,{data}")'

    out = re.sub(r"asset\(([\w.\-]+)\)", sub, css)
    if missing:
        print("WARNING: missing art files, their URLs were left relative instead of inlined:",
              ", ".join(sorted(set(missing))))
        print("         Put the files in skin/skin-dev/assets/ and run this again.")
    return out


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "css"), exist_ok=True)
    gen = tokens()
    open(os.path.join(HERE, "css", "10-tokens.gen.css"), "w", encoding="utf-8", newline="\n").write(gen)
    parts = [gen]
    decor = os.path.join(HERE, "css", "20-decor.css")
    if os.path.exists(decor):
        parts.append(open(decor, encoding="utf-8").read())
    css = inline_assets("\n".join(parts))
    tmp = OUT + ".tmp"
    open(tmp, "w", encoding="utf-8", newline="\n").write(css)
    os.replace(tmp, OUT)
    print(f"wrote {OUT} ({len(css) / 1024:.0f} KB, {gen.count('!important')} token overrides)")
